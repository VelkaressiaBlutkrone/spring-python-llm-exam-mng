# 정상 → 정상 매핑 제거 (오타만 남김)
MEDICAL_TYPO_MAP = {k: v for k, v in MEDICAL_TYPO_MAP.items() if k != v}


def correct_typos(text: str) -> str:
    """
    의료 용어 오타를 사전 기반으로 교정한다.
    긴 키워드부터 먼저 매칭하여 부분 치환 충돌을 방지한다.

    Args:
        text: 원본 텍스트

    Returns:
        교정된 텍스트 (변경 없으면 원본 그대로)
    """
    if not text:
        return text

    corrected = text
    corrections = []

    # 긴 키워드부터 매칭 (부분 매칭 충돌 방지)
    sorted_typos = sorted(MEDICAL_TYPO_MAP.keys(), key=len, reverse=True)

    for typo in sorted_typos:
        if typo in corrected:
            correct = MEDICAL_TYPO_MAP[typo]
            corrected = corrected.replace(typo, correct)
            corrections.append(f"'{typo}'→'{correct}'")

    if corrections:
        logger.info("Typo corrected: %s", ", ".join(corrections))

    return corrected
